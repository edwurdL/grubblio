// Prints the SQL that Better Auth's tables need for the settings in
// server/auth.ts, compared against the tables migrations/ already create.
// Run it after changing those settings or upgrading better-auth, and save any
// output as the next migration:
//
//   npm run auth:schema > migrations/000N_auth_update.sql
//
// It replays migrations/*.sql into an in-memory SQLite database, so it needs no
// Cloudflare account and never touches D1.
import { readdirSync, readFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { getMigrations } from 'better-auth/db/migration';
import { authOptions } from '../server/auth';

const dir = new URL('../migrations/', import.meta.url);
const db = new DatabaseSync(':memory:');
for (const file of readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()) {
  db.exec(readFileSync(new URL(file, dir), 'utf8'));
}

const options = authOptions(db, 'http://localhost', 'schema-only', async () => {});
const { compileMigrations, toBeCreated, toBeAdded } = await getMigrations(options);
if (!toBeCreated.length && !toBeAdded.length) {
  console.error('Better Auth tables are up to date; no migration needed.');
} else {
  console.log('-- Better Auth tables (generated by `npm run auth:schema`).');
  console.log(await compileMigrations());
}
